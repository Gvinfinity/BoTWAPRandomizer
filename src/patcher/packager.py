import zipfile
import os
import shutil

def create_graphic_pack(output_zip: str, modified_files_dir: str, hook_dir: str):
    """
    Zips up the generated BYML files alongside the C++ DLL and patches.txt
    to create a complete Cemu Graphic Pack for the player.
    """
    print(f"Creating graphic pack at {output_zip}...")
    
    with zipfile.ZipFile(output_zip, 'w', zipfile.ZIP_DEFLATED) as zf:
        # 1. Add modified map files (.bdrop, .bshop, etc)
        if os.path.exists(modified_files_dir):
            for root, _, files in os.walk(modified_files_dir):
                for file in files:
                    file_path = os.path.join(root, file)
                    arcname = os.path.relpath(file_path, modified_files_dir)
                    # Put inside the romfs structure
                    zf.write(file_path, f"content/{arcname}")
                    
        # 2. Add Cemu patch rules and hook dll
        if os.path.exists(hook_dir):
            rules_path = os.path.join(hook_dir, 'rules.txt')
            patches_path = os.path.join(hook_dir, 'patches.txt')
            
            if os.path.exists(rules_path):
                zf.write(rules_path, 'rules.txt')
            if os.path.exists(patches_path):
                zf.write(patches_path, 'patches.txt')
                
            # Find the compiled DLL or SO
            for file in os.listdir(hook_dir):
                if file.endswith('.dll') or file.endswith('.so'):
                    zf.write(os.path.join(hook_dir, file), file)
                    
    print("Graphic Pack generation complete.")

