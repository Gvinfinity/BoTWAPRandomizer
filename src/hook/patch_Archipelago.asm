    addi r4, r3, 0x4C
    lis r12, 0x02EB
    ori r12, r12, 0x3764
    mtctr r12
    bctrl

injection_unlock:
    # unlock(mgr + 0x10)
    lwz r3, 0x58(r1)
    addi r3, r3, 0x10
    lis r12, 0x030B
    ori r12, r12, 0xB69C
    mtctr r12
    bctrl

