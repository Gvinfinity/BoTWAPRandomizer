    lis r12, 0x0308
    ori r12, r12, 0x812C
    mtctr r12
    bctrl
    stw r3, 0x60(r1)                 # full durability

pouch_value_ready:

    # -------------------------------------------------------------------------
    # addItem(mgr, &SafeString, type, mgr + 0x4c, value, 0, 0, 0)
    # -------------------------------------------------------------------------
    lwz r3, 0x58(r1)                 # mgr
    addi r4, r1, 0x50                # SafeString*
    lwz r5, 0x64(r1)                 # PouchItemType
    addi r6, r3, 0x4C                # OffsetList head
    lwz r7, 0x60(r1)                 # value / full durability
    li r8, 0
    li r9, 0
    li r10, 0

    lis r12, 0x02EB
    ori r12, r12, 0x3DF0
    mtctr r12
    bctrl

    # -------------------------------------------------------------------------
    # The 0x02EB58A8 follow-up is used by the game's food-tagged add wrapper.
    # Calling it for weapons crashes in its actor-info path (observed at
    # 0x02EC216C). Keep it limited to PouchItemType 8 (Food).
    # -------------------------------------------------------------------------
    lwz r5, 0x64(r1)
    cmpwi r5, 8
    bne save_item_data

    lwz r3, 0x58(r1)
    addi r4, r1, 0x50
    lis r12, 0x02EB
    ori r12, r12, 0x58A8
    mtctr r12
    bctrl

save_item_data:
    lwz r3, 0x58(r1)
    addi r4, r3, 0x4C
    lis r12, 0x02EB
    ori r12, r12, 0x3764
    mtctr r12
    bctrl

injection_unlock:
    # unlock(mgr + 0x10)
    lwz r3, 0x58(r1)
    addi r3, r3, 0x10
    lis r12, 0x030B
    ori r12, r12, 0xB69C
    mtctr r12
    bctrl

    # Clear injection guard.
    lis r9, _AP_Is_Injecting@ha
    addi r9, r9, _AP_Is_Injecting@l
    li r10, 0
    stw r10, 0(r9)

