    lfd f7,  0xB8(r1)
    lfd f8,  0xC0(r1)
    lfd f9,  0xC8(r1)
    lfd f10, 0xD0(r1)
    lfd f11, 0xD8(r1)
    lfd f12, 0xE0(r1)
    lfd f13, 0xE8(r1)

    lwz r3, 0x08(r1)
    lwz r4, 0x0C(r1)
    lwz r5, 0x10(r1)
    lwz r6, 0x14(r1)
    lwz r7, 0x18(r1)
    lwz r8, 0x1C(r1)
    lwz r9, 0x20(r1)
    lwz r10, 0x24(r1)
    lwz r11, 0x28(r1)
    lwz r12, 0x2C(r1)

    lwz r0, 0x7C(r1)
    mtlr r0
    lwz r0, 0x30(r1)
    addi r1, r1, 0xF0

